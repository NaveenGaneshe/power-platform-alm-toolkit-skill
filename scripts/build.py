#!/usr/bin/env python3
"""Build distributable packages for every skill under skills/.

Output (dist/):
  <skill>.zip                         Skill folder zipped. Upload to Claude apps (Settings > Capabilities > Skills),
                                      or unzip into any Agent Skills directory.
  portable/<skill>.md                 Single-file bundle: SKILL.md + every reference and asset inlined.
                                      For tools without skill support (ChatGPT custom GPTs, Gemini Gems,
                                      Microsoft Copilot Studio, Claude Projects, any chat model).
  portable/<skill>.instructions.md    Short system instructions (< 8,000 characters) that point the assistant
                                      at the bundle uploaded as a knowledge file.
  SHA256SUMS.txt                      Checksums for release verification.

Usage: python3 scripts/build.py   (runs validate.py first and stops on errors)
Standard library only.
"""
from __future__ import annotations

import hashlib
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
DIST = ROOT / "dist"
TEXT_SUFFIXES = {".md", ".txt", ".json", ".yml", ".yaml", ".ps1", ".psm1", ".py", ".sh", ".xml", ".csv"}
FENCE_LANG = {".psm1": "powershell", ".ps1": "powershell", ".json": "json", ".yml": "yaml",
              ".yaml": "yaml", ".py": "python", ".sh": "bash", ".xml": "xml", ".csv": "csv"}
INSTRUCTIONS_LIMIT = 8000


def files_of(skill: Path) -> list[Path]:
    return sorted(p for p in skill.rglob("*") if p.is_file() and "__pycache__" not in p.parts and p.name != ".DS_Store")


def build_zip(skill: Path) -> Path:
    out = DIST / f"{skill.name}.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in files_of(skill):
            # Folder at the zip root must match the skill name (Claude upload requirement).
            zf.write(f, Path(skill.name) / f.relative_to(skill))
    return out


def fence_for(text: str) -> str:
    # Use a fence longer than any backtick run inside the file so nested code blocks survive.
    longest = max((len(run) for run in __import__("re").findall(r"`+", text)), default=0)
    return "`" * max(4, longest + 1)


def build_portable(skill: Path) -> tuple[Path, Path]:
    portable = DIST / "portable"
    portable.mkdir(parents=True, exist_ok=True)
    skill_md = (skill / "SKILL.md").read_text(encoding="utf-8")
    parts = [
        f"<!-- Portable bundle of the '{skill.name}' Agent Skill. Generated by scripts/build.py; do not edit by hand. -->",
        "",
        "# How to use this file",
        "",
        "This single file contains a complete skill: the main instructions (SKILL.md) followed by every",
        "supporting file. Wherever the instructions mention a path such as `references/tooling.md` or",
        "`assets/Dataverse.psm1`, use the section with that path as its heading further down this file.",
        "",
        "---",
        "",
        "## File: SKILL.md",
        "",
        skill_md.strip(),
        "",
    ]
    for f in files_of(skill):
        rel = f.relative_to(skill).as_posix()
        if rel == "SKILL.md" or f.suffix.lower() not in TEXT_SUFFIXES:
            continue
        text = f.read_text(encoding="utf-8")
        parts += ["---", "", f"## File: {rel}", ""]
        if f.suffix.lower() == ".md":
            parts.append(text.strip())
        else:
            fence = fence_for(text)
            parts += [f"{fence}{FENCE_LANG.get(f.suffix.lower(), '')}", text.rstrip(), fence]
        parts.append("")
    bundle = portable / f"{skill.name}.md"
    bundle.write_text("\n".join(parts), encoding="utf-8")

    instructions = f"""You are an Elite Enterprise Cloud Architect and Automated Application Lifecycle Management (ALM) engineer for Microsoft Power Platform.

Your knowledge files include `{skill.name}.md`. It is your complete operating manual: a skill named "{skill.name}" (its main instructions, followed by its reference files and assets).

For every request about Power Platform, Dataverse, Dynamics 365, Power Automate, Power Apps, PAC CLI, custom connectors, Custom APIs, PCF controls, solution ALM, bulk data or user/role administration, or GitHub Actions pipelines for Power Platform:
1. Read the "File: SKILL.md" section of `{skill.name}.md` and follow it exactly. It defines the four-part blueprint (1. Core Operational Capability Mapping, 2. Extended Solution Architecture & Schemas, 3. Repository Directory Structure & ALM Pipelines, 4. End-User & Developer Runbooks).
2. When it points to a path such as `references/tooling.md` or `assets/Dataverse.psm1`, open the section headed "File: <that path>" in the same knowledge file before writing code. Use the exact command names, parameters and action inputs given there; never invent flags.
3. Deliver complete, runnable files. Put each file in its own code block headed by its repository path.
4. Anything that changes data must default to a test run that changes nothing, save a snapshot before changing records, and include an undo path in the runbook.
5. Never put secrets, environment URLs or tenant IDs in code. Use parameters, GitHub environment variables and secrets.
6. Answer quick questions directly; produce the full blueprint only when the user asks for a module, pipeline or operation.

If the knowledge file is unavailable, say so and ask the user to upload `{skill.name}.md` rather than improvising.
"""
    if len(instructions) > INSTRUCTIONS_LIMIT:
        raise SystemExit(f"instructions for {skill.name} exceed {INSTRUCTIONS_LIMIT} characters")
    instr = portable / f"{skill.name}.instructions.md"
    instr.write_text(instructions, encoding="utf-8")
    return bundle, instr


def main() -> int:
    if subprocess.call([sys.executable, str(ROOT / "scripts" / "validate.py"), str(SKILLS)]) != 0:
        print("Validation failed; not building.")
        return 1
    DIST.mkdir(exist_ok=True)
    outputs: list[Path] = []
    for skill in sorted(p for p in SKILLS.iterdir() if p.is_dir()):
        outputs.append(build_zip(skill))
        outputs.extend(build_portable(skill))
    sums = [f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.relative_to(DIST).as_posix()}" for p in outputs]
    (DIST / "SHA256SUMS.txt").write_text("\n".join(sums) + "\n", encoding="utf-8")
    for p in outputs:
        print(f"built {p.relative_to(ROOT)} ({p.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
